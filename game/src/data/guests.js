function idFromArt(art) {
  return art?.match(/guest_(.+)_web\.jpg$/)?.[1] || null;
}

const entries = new Map();
for (const level of FATE_PUZZLES) {
  const id = idFromArt(level.guest.art) || level.guest.name;
  if (!entries.has(id)) {
    entries.set(id, { id, ...level.guest, fateLevels: [], brewLevels: [] });
  }
  entries.get(id).fateLevels.push(level.id);
}

// Варка использует те же знакомые лица, но фея встречается только у котла.
for (const [brewId, source] of Object.entries(BREW_GUESTS)) {
  const levels = Object.entries(BREW_LEVEL_GUESTS)
    .filter(([, guestId]) => guestId === brewId)
    .map(([levelId]) => levelId);
  const existing = [...entries.values()].find((entry) => (
    (source.art && entry.art === source.art) || entry.name === source.name
  ));
  if (existing) {
    existing.brewLevels.push(...levels);
  } else {
    const id = idFromArt(source.art) || brewId;
    entries.set(id, { id, ...source, fateLevels: [], brewLevels: levels });
  }
}

export const GUESTS = [...entries.values()].map((guest) => {
  const detail = DETAILS[guest.id];
  if (!detail) throw new Error(`Нет описания гостевой книги для ${guest.id}`);
  return { ...guest, ...detail };
});

export const GUEST_BY_ID = Object.fromEntries(GUESTS.map((guest) => [guest.id, guest]));

export function guestKnown(state, guest) {
  return [...guest.fateLevels, ...guest.brewLevels]
    .some((levelId) => !!state.puzzlesDone?.[levelId]);
}
